export class ReviewStore {
  constructor() {
    this.byRecipe = new Map(sampleTexts.map((texts, index) => [index + 1, texts.map((body, offset) => ({
      id: `demo-${index + 1}-${offset + 1}`, recipeId: index + 1,
      userId: index * 2 + offset + 1, rating: offset ? 4 : 5, body, source: 'demo'
    }))]));
    this.nextId = 1;
  }
  get(recipeId) { return (this.byRecipe.get(Number(recipeId)) || []).map(review => ({ ...review })); }
  add({ recipeId, userId, rating, body }, users) {
    recipeId = Number(recipeId); userId = Number(userId); rating = Number(rating); body = String(body ?? '').trim();
    if (!Number.isInteger(recipeId) || recipeId <= 0) throw new Error('Рецепт не найден.');
    if (!Number.isInteger(userId) || !users.some(user => user.id === userId)) throw new Error('Выберите автора из списка.');
    if (!Number.isInteger(rating) || rating < 1 || rating > 5) throw new Error('Выберите оценку от 1 до 5.');
    if (!body || body.length > 1000) throw new Error('Напишите отзыв длиной от 1 до 1000 символов.');
    const review = { id: `local-${this.nextId++}`, recipeId, userId, rating, body, source: 'local' };
    const reviews = this.byRecipe.get(recipeId) || [];
    this.byRecipe.set(recipeId, [review, ...reviews]);
    return { ...review };
  }
}
